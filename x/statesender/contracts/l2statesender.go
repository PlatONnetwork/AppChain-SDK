func (c *L2StateSender) SyncStateEntry(input []byte) ([]byte, error) {

	method := c.abi.Methods["syncState"]

	var err error

	args, err := method.Inputs.Unpack(input)
	if err != nil {
		return nil, err
	}

	err = c.SyncState(*abi.ConvertType(args[0], new(common.Address)).(*common.Address), *abi.ConvertType(args[1], new([]byte)).(*[]byte))
	if err != nil {
		if r, ok := err.(*typesdk.RevertError); ok {
			return r.ReturnData, vm.ErrExecutionReverted
		}
		return nil, err
	}
	var output []byte

	return output, err
}

func (c *L2StateSender) L2StateSyncedEvent(id *big.Int, sender common.Address, receiver common.Address, callData []byte) (*types.Log, error) {
	event := c.abi.Events["L2StateSynced"]
	hashes, err := contracts.PackEventTopics(event.ID, event.Inputs, id, sender, receiver, callData)
	if err != nil {
		return nil, err
	}
	data, err := contracts.PackEventData(event.Inputs, id, sender, receiver, callData)
	if err != nil {
		return nil, err
	}
	return &types.Log{
		Address:     c.contract.Address(),
		Topics:      hashes,
		Data:        data,
		BlockNumber: c.evm.Context.BlockNumber.Uint64(),
	}, nil
}
func (c *L2StateSender) EmitL2StateSyncedEvent(id *big.Int, sender common.Address, receiver common.Address, callData []byte) {
	log, err := c.L2StateSyncedEvent(id, sender, receiver, callData)
	contracts.Require(err == nil, "L2StateSender: emit L2StateSynced event failed")
	c.stateDb.AddLog(log)
}
